def deployment_diagram(cfg: dict, pol: dict) -> str:
    providers = cfg.get("providers") or {}
    cls = cfg.get("classifier") or {}
    entities = (pol.get("classification") or {}).get("pii_entities") or []

    lines = [
        "```mermaid",
        "flowchart LR",
        '  CALLER(["support agent<br/>or automation"]) -->|"bearer token"| GW',
        '  subgraph ON["on-premises boundary"]',
        '    GW["<b>gateway</b><br/>FastAPI, one event loop'
        '<br/>policy, guards, audit, metrics"]',
        f'    CLS["<b>classifier</b><br/>{esc(cls.get("type"))}: '
        f'{esc(join(cls.get("members") or []))}'
        f'<br/>{len(entities)} entity types, fail-closed"]',
    ]
    for name, p in providers.items():
        if p.get("zone") == "onprem":
            lines.append(f'    P_{name}["{esc(name)}<br/>{esc(p.get("model"))}'
                         f'<br/>${p.get("cost_per_1k")}/1k"]')
    lines += ["  end", '  subgraph CL["cloud"]']
    for name, p in providers.items():
        if p.get("zone") == "cloud":
            lines.append(f'    P_{name}["{esc(name)}<br/>{esc(p.get("model"))}'
                         f'<br/>${p.get("cost_per_1k")}/1k"]')
    lines += ["  end", '  GW -->|"classify first"| CLS']
    for name, p in providers.items():
        label = ("personal data, or cloud unavailable"
                 if p.get("zone") == "onprem" else "ONLY if no personal data")
        lines.append(f'  GW -->|"{label}"| P_{name}')
    lines += [
        '  GW --> AUDIT[("audit trail<br/>and cost ledger")]',
        '  GW --> PROM[("Prometheus /metrics<br/>'
        'CPU, memory, event-loop lag")]',
        "",
        "  classDef svc fill:#eef4ff,stroke:#4169b2,color:#10243f;",
        "  classDef store fill:#f2f0ea,stroke:#8a8372,color:#2b2823;",
        "  class GW,CLS svc;",
        "  class AUDIT,PROM store;",
        "```",
    ]
    return "\n".join(lines)


