def module_name(path: Path) -> str:
    rel = path.relative_to(GATEWAY).with_suffix("")
    return ".".join(rel.parts)


def reexport_map(files: list[Path]) -> dict[tuple[str, str], str]:
    """Where a symbol re-exported by a package actually lives.

    `providers/__init__.py` does `from .anthropic_provider import
    AnthropicProvider`, so `from providers import AnthropicProvider` in
    factory.py is really an edge to providers.anthropic_provider.

    Without following that, every provider import collapses to the
    package name, the adapter-boundary check never matches anything, and
    it becomes a test that cannot fail - the same defect removed from
    verify.py earlier, where a rounded number was compared against
    itself. A graph that is merely coarse is fine; an invariant that
    cannot be violated is not.
    """
    out: dict[tuple[str, str], str] = {}
    for path in files:
        if path.name != "__init__.py":
            continue
        pkg = module_name(path)[: -len(".__init__")]
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        for node in ast.walk(tree):
            if not isinstance(node, ast.ImportFrom):
                continue
            # `from .base import X` - level 1, module "base"
            target = (f"{pkg}.{node.module}" if node.level and node.module
                      else node.module)
            if not target:
                continue
            for alias in node.names:
                out[(pkg, alias.asname or alias.name)] = target
    return out


def build_module_graph() -> tuple[dict[str, set[str]], list[str]]:
    """Local import edges between the gateway's own modules.

    Only edges to modules that exist in this tree are kept: the point is
    the shape of OUR code, and a list of standard-library imports would
    bury it.
    """
    files = [p for p in GATEWAY.rglob("*.py")
             if "tests" not in p.parts and ".venv" not in p.parts]
    known = {module_name(p) for p in files}
    known |= {m[: -len(".__init__")] for m in list(known)
              if m.endswith(".__init__")}
    reexports = reexport_map(files)

    edges: dict[str, set[str]] = {}
    for path in files:
        me = module_name(path)
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except SyntaxError:
            continue
        targets: set[str] = set()
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                for a in node.names:
                    if a.name in known:
                        targets.add(a.name)
            elif isinstance(node, ast.ImportFrom) and node.module:
                mod = node.module
                resolved_any = False
                for a in node.names:
                    if f"{mod}.{a.name}" in known:       # from pkg import mod
                        targets.add(f"{mod}.{a.name}")
                        resolved_any = True
                    elif (mod, a.name) in reexports:     # through __init__
                        targets.add(reexports[(mod, a.name)])
                        resolved_any = True
                if not resolved_any and mod in known:
                    targets.add(mod)
        targets.discard(me)
        targets.discard(me[: -len(".__init__")] if me.endswith(".__init__")
                        else me)
        if targets:
            edges[me] = targets

    # The invariant, computed rather than asserted.
    concrete = {m for m in known if m.startswith("providers.")
                and m not in ("providers.base", "providers.__init__")}
    violations = sorted(
        f"{src} imports {dst}"
        for src, dsts in edges.items()
        for dst in dsts
        if dst in concrete and src not in ALLOWED_VENDOR_IMPORTERS
    )
    return edges, violations


def module_diagram(edges: dict[str, set[str]]) -> str:
    def nid(m: str) -> str:
        return m.replace(".", "_").replace("-", "_")

    # Every node, not just the ones that import something. A leaf like
    # observability.py or providers/base.py has no outgoing local import,
    # and keying off edges alone left those floating outside their
    # subgraph - which read as "not part of the system".
    nodes = set(edges) | {d for dsts in edges.values() for d in dsts}

    # providers/base.py is the CONTRACT, not an adapter. It names no
    # vendor - it is the interface every adapter implements and the one
    # thing routing.py is allowed to depend on. Grouping it with the
    # concrete providers under "vendor code" would contradict the point
    # the diagram exists to make.
    contract = [m for m in ("providers.base",) if m in nodes]
    adapters = sorted(m for m in nodes
                      if m.startswith("providers") and m not in contract)
    classifiers = sorted(m for m in nodes if m.startswith("classifiers"))
    core = [m for m in ("main", "factory") if m in nodes]
    domain = sorted(m for m in nodes
                    if m not in core
                    and not m.startswith(("providers", "classifiers")))

    lines = ["```mermaid", "flowchart TB",
             '  subgraph G1["entry and construction"]']
    for m in core:
        lines.append(f'    {nid(m)}["{m}.py"]')
    lines.append("  end")
    if domain:
        lines.append('  subgraph G2["domain - no vendor name appears here"]')
        for m in domain:
            lines.append(f'    {nid(m)}["{m}.py"]')
        lines.append("  end")
    if contract:
        lines.append('  subgraph G3a["the contract - names no vendor"]')
        for m in contract:
            lines.append(f'    {nid(m)}["{m}"]')
        lines.append("  end")
    if adapters:
        lines.append('  subgraph G3["adapters - the ONLY vendor code"]')
        for m in adapters:
            lines.append(f'    {nid(m)}["{m}"]')
        lines.append("  end")
    if classifiers:
        lines.append('  subgraph G4["classifiers"]')
        for m in classifiers:
            lines.append(f'    {nid(m)}["{m}"]')
        lines.append("  end")

    for src in sorted(edges):
        for dst in sorted(edges[src]):
            lines.append(f"  {nid(src)} --> {nid(dst)}")

    lines.append("")
    lines.append("  classDef vendor fill:#fff1e8,stroke:#c2621d,color:#3f2410;")
    if adapters:
        lines.append("  class " + ",".join(nid(m) for m in adapters)
                     + " vendor;")
    lines.append("```")
    return "\n".join(lines)


# --------------------------------------------------------------------------


def build() -> str:
    cfg, pol = load()
    providers = cfg.get("providers") or {}
    onprem = sum(1 for p in providers.values() if p.get("zone") == "onprem")
    cloud = sum(1 for p in providers.values() if p.get("zone") == "cloud")
    constraints = pol.get("constraints") or []
    edges, violations = build_module_graph()

    out = [
        "### The request path",
        "",
        "Every call takes the same six stages.",
        "",
        pipeline_diagram(cfg, pol),
        "",
        "### The decision at stage 2",
        "",
        "This is the one the system exists to make, so it gets its own "
        "picture rather than four arrows crowding the diagram above. "
        "**Personal data filters the provider list before cost or latency "
        "are consulted.** A preference can be outvoted; a constraint cannot.",
        "",
        decision_diagram(cfg, pol),
        "",
        "Constraints in force, read from `policy.yaml`:",
        "",
    ]
    for c in constraints:
        when = ", ".join(f"`{k}: {v}`" for k, v in (c.get("when") or {}).items())
        out.append(f"- **`{c.get('name')}`** - when {when}, require zone "
                   f"`{c.get('require_zone')}`")
    out += [
        "",
        "The second is the one worth pausing on. If the classifier is "
        "unreachable the gateway cannot *prove* a payload is free of personal "
        "data, and inability to prove absence is treated as presence. The "
        "subscriber is still served, on-premises. Safety without an outage.",
        "",
        "### Deployment",
        "",
        f"{onprem} providers on-premises, {cloud} in cloud, and a classifier "
        "that gates the boundary.",
        "",
        deployment_diagram(cfg, pol),
        "",
        "### Modules, parsed from the imports",
        "",
        f"Not drawn. This is the real import graph of {len(edges)} modules.",
        "",
        module_diagram(edges),
        "",
    ]
    if violations:
        out += ["> **Adapter boundary violated.** These modules import a "
                "concrete provider and should not:", ""]
        out += [f"> - `{v}`" for v in violations]
    else:
        out += [
            "**The Adapter boundary holds.** No module outside `factory.py` "
            "and the providers package imports a concrete provider - not "
            "`main.py`, not `routing.py`, not `policy.py`. `routing.py` "
            "depends only on `policy` and `providers/base`, so it orders and "
            "falls back between providers it knows nothing about. That is "
            "what makes swapping a model a configuration line rather than a "
            "release, and `architecture.py --check` fails the build if it "
            "ever stops being true.",
        ]
    out += [
        "",
        "_All four diagrams are generated by `architecture.py` from "
        "`config.yaml`, `policy.yaml` and the import graph. CI runs "
        "`--check` and fails if they drift._",
    ]
    return "\n".join(out)


def splice(readme: str, block: str) -> str:
    body = f"{BEGIN}\n\n{block}\n\n{END}"
    if BEGIN in readme and END in readme:
        return (readme[:readme.index(BEGIN)] + body
                + readme[readme.index(END) + len(END):])
    marker = "\n## Findings\n"
    if marker in readme:
        i = readme.index(marker)
        return (readme[:i] + "\n---\n\n## Architecture\n\n" + body + "\n"
                + readme[i:])
    return readme.rstrip() + "\n\n---\n\n## Architecture\n\n" + body + "\n"


def main() -> int:
    # Generated text and the files it lands in are UTF-8; a Windows console
    # is cp1252 and one arrow in a preview is enough to raise. The diagram
    # should not be degraded for the file because a terminal cannot show it.
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    ap = argparse.ArgumentParser(description="Generate architecture diagrams.")
    ap.add_argument("--write", action="store_true", help="update README.md")
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if README.md has drifted from the code")
    args = ap.parse_args()

    _, violations = build_module_graph()
    block = build()

    if args.check:
        current = README.read_text(encoding="utf-8")
        problems = []
        if BEGIN not in current or END not in current:
            problems.append("README has no generated architecture block")
        else:
            start = current.index(BEGIN) + len(BEGIN)
            if current[start:current.index(END)].strip() != block.strip():
                problems.append("README diagrams no longer match the code "
                                "or the configuration")
        if violations:
            problems.append("adapter boundary violated: "
                            + "; ".join(violations))
        if problems:
            for p in problems:
                print(f"  FAIL  {p}")
            print("\n  Run: python architecture.py --write")
            return 1
        print("  architecture diagrams match the code and configuration")
        print("  adapter boundary holds: only factory.py imports a vendor")
        return 0

    if args.write:
        current = README.read_text(encoding="utf-8")
        updated = splice(current, block)
        if updated == current:
            print("  README already up to date")
        else:
            README.write_text(updated, encoding="utf-8")
            print(f"  README.md updated ({len(block)} characters)")
        if violations:
            print("  WARNING adapter boundary violated:")
            for v in violations:
                print(f"    {v}")
        return 0

    print(block)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
