def decision_diagram(cfg: dict, pol: dict) -> str:
    providers = cfg.get("providers") or {}
    onprem = [n for n, p in providers.items() if p.get("zone") == "onprem"]
    cloud = [n for n, p in providers.items() if p.get("zone") == "cloud"]
    refuse = pol.get("on_no_allowed_provider")
    order = " then ".join((pol.get("selection") or {}).get("order") or [])

    return "\n".join([
        "```mermaid",
        "flowchart TB",
        '  IN(["payload"]) --> HEALTHY{"classifier<br/>healthy?"}',
        '  HEALTHY -->|"no"| FC["cannot PROVE absence<br/>'
        'so treat as present"]',
        '  HEALTHY -->|"yes"| PII{"carries<br/>personal data?"}',
        '  PII -->|"yes"| FC2["hard constraint"]',
        '  PII -->|"no"| OPEN["no zone constraint"]',
        f'  FC --> ONLY["allowlist: on-prem only<br/>{esc(join(onprem))}"]',
        "  FC2 --> ONLY",
        f'  OPEN --> ALL["allowlist: all providers<br/>'
        f'{esc(join(onprem + cloud))}"]',
        '  ONLY --> PICK{"any allowed<br/>provider healthy?"}',
        "  ALL --> PICK",
        f'  PICK -->|"yes"| SEL["rank by {esc(order)}"]',
        f'  PICK -->|"no"| NO["{esc(refuse)}<br/>'
        'a refusal is a result<br/>a silent downgrade is a breach"]',
        "",
        "  classDef q fill:#fffbe6,stroke:#b59a00,color:#3d3300;",
        "  classDef hard fill:#fff1e8,stroke:#c2621d,color:#3f2410;",
        "  classDef ok fill:#eaf7ee,stroke:#2f8f4e,color:#123020;",
        "  classDef stop fill:#ffe9e9,stroke:#b33,color:#3f1010;",
        "  class HEALTHY,PII,PICK q;",
        "  class FC,FC2,ONLY hard;",
        "  class OPEN,ALL,SEL ok;",
        "  class NO stop;",
        "```",
    ])


