"""Generate the architecture diagrams FROM the code and the configuration.

A hand-drawn diagram is a claim about a system, and like every other
hand-written claim in this project it goes stale the moment the system
moves. The requirements file that invented seven versions and the gate
count that came from grepping prose were both that mistake. So nothing
here is drawn: model names, zones, costs, guard names, constraints and
the chain deadline come from config.yaml and policy.yaml, and the module
graph comes from parsing the imports.

    python architecture.py              # print the diagrams
    python architecture.py --write      # update README.md between markers
    python architecture.py --check      # fail if README has drifted

--check is what continuous integration runs. Add a provider, rename a
guard or make routing import a vendor, and the build fails rather than
the diagram quietly lying to the next reader.

THE ADAPTER BOUNDARY IS CHECKED, NOT DESCRIBED. BUSINESS_CASE.md claims
the gateway is vendor-blind by construction. That is either true of the
import graph or it is marketing, so build_module_graph() works out which
modules import a concrete provider and the diagram reports it. Verified
independently against a Graphify index of this repository at ae954c8:
providers/anthropic_provider.py has exactly one importer outside its own
package, and it is factory.py.

Mermaid, because GitHub renders it natively in README files and in
workflow job summaries - no image to regenerate, no binary in the repo,
and the diagram stays diffable in review.
"""

from __future__ import annotations

import argparse
import ast
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent
GATEWAY = ROOT / "llm-gateway"
README = ROOT / "README.md"

BEGIN = "<!-- ARCHITECTURE:BEGIN - generated by architecture.py, do not edit -->"
END = "<!-- ARCHITECTURE:END -->"

# The six stages are structural rather than configured - they ARE the
# pipeline, documented in ARCHITECTURE.md section 3. Everything that hangs
# off them below is read from the configuration.
STAGES = [
    ("CLASSIFY", "does this payload carry personal data?"),
    ("POLICY", "which providers are even ALLOWED?"),
    ("SELECT", "of those allowed, which is best?"),
    ("GUARD-IN", "is the input safe?"),
    ("CALL", "invoke the provider through the Adapter"),
    ("GUARD-OUT", "is the output safe to return?"),
]

# Modules whose job is to know a vendor. Anything else importing a
# concrete provider has crossed the Adapter boundary.
ALLOWED_VENDOR_IMPORTERS = {"factory", "providers.__init__", "providers"}


def load() -> tuple[dict, dict]:
    cfg = yaml.safe_load((GATEWAY / "config.yaml").read_text(encoding="utf-8"))
    pol = yaml.safe_load((GATEWAY / "policy.yaml").read_text(encoding="utf-8"))
    return cfg or {}, pol or {}


def esc(text: object) -> str:
    """Mermaid labels are double-quoted; the quote is the only hazard."""
    return str(text).replace('"', "'")


def join(items) -> str:
    return ", ".join(str(i) for i in items)


# --------------------------------------------------------------------------
# 1. The request path
# --------------------------------------------------------------------------


def pipeline_diagram(cfg: dict, pol: dict) -> str:
    """Six stages, left to right, with nothing branching off them.

    An earlier version hung the policy outcomes off stage 2 in this same
    diagram. Mermaid laid those branches out along the main axis and
    pushed stages 3 to 6 sideways, so the exceptions read as the happy
    path. The decision gets its own diagram instead - it is the most
    important thing here and should not be a footnote on a crowded one.
    """
    cls = cfg.get("classifier") or {}
    guards = cfg.get("guardrails") or {}
    gin = [g.get("name") or g.get("type") for g in (guards.get("input") or [])]
    gout = [g.get("name") or g.get("type") for g in (guards.get("output") or [])]
    order = " then ".join((pol.get("selection") or {}).get("order") or [])
    deadline = (pol.get("routing") or {}).get("chain_deadline_s")

    detail = {
        "CLASSIFY": f"{cls.get('type')}: {join(cls.get('members') or [])}",
        "POLICY": "hard constraints<br/>filter the allowlist",
        "SELECT": order or "health then cost then latency",
        "GUARD-IN": join(gin) or "none",
        "CALL": f"fallback chain<br/>{deadline}s deadline",
        "GUARD-OUT": join(gout) or "none",
    }

    lines = ["```mermaid", "flowchart LR", '  REQ(["request"]) --> S1']
    for i, (name, why) in enumerate(STAGES, start=1):
        lines.append(f'  S{i}["<b>{i} {name}</b><br/><i>{esc(why)}</i>'
                     f'<br/>{esc(detail[name])}"]')
    for i in range(1, len(STAGES)):
        lines.append(f"  S{i} --> S{i + 1}")
    lines += [
        f'  S{len(STAGES)} --> RESP(["response"])',
        '  S6 --> AUDIT[("audit trail<br/>one JSON line, always")]',
        "",
        "  classDef stage fill:#eef4ff,stroke:#4169b2,color:#10243f;",
        "  classDef store fill:#f2f0ea,stroke:#8a8372,color:#2b2823;",
        f"  class {','.join('S%d' % i for i in range(1, len(STAGES) + 1))} stage;",
        "  class AUDIT store;",
        "```",
    ]
    return "\n".join(lines)


